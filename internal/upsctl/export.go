package upsctl

import (
	"context"
	"encoding/json"
	"fmt"
	"slices"
	"strings"

	"sigs.k8s.io/yaml"
)

// ExportHeader starts every exported spec.
const ExportHeader = "# generated by upsctl, secrets are ${ENV} placeholders\n"

// Export reads the live team and renders it as a YAML spec. Secret values
// never appear: the API redacts them and they are written as ${ENV}
// placeholders. Warnings describe anything that could not be exported
// faithfully.
func Export(ctx context.Context, api API) ([]byte, []string, error) {
	live, err := FetchLive(ctx, api)
	if err != nil {
		return nil, nil, err
	}
	s, warnings, err := SpecFromLive(live)
	if err != nil {
		return nil, nil, err
	}
	out, err := MarshalSpec(s)
	return out, warnings, err
}

// MarshalSpec renders a spec as YAML with the export header, version first.
// Keys are sorted, so the output is deterministic.
func MarshalSpec(s *Spec) ([]byte, error) {
	body := *s
	body.Version = 0
	b, err := json.Marshal(struct {
		Channels           []ChannelSpec    `json:"channels,omitempty"`
		EscalationPolicies []PolicySpec     `json:"escalation_policies,omitempty"`
		Monitors           []MonitorSpec    `json:"monitors,omitempty"`
		StatusPages        []StatusPageSpec `json:"status_pages,omitempty"`
	}{body.Channels, body.EscalationPolicies, body.Monitors, body.StatusPages})
	if err != nil {
		return nil, err
	}
	y, err := yaml.JSONToYAML(b)
	if err != nil {
		return nil, err
	}
	if strings.TrimSpace(string(y)) == "{}" {
		y = nil
	}
	return append([]byte(fmt.Sprintf("%sversion: %d\n", ExportHeader, SpecVersion)), y...), nil
}

// SpecFromLive converts a live snapshot to a spec: names instead of ids,
// no ids or timestamps, sorted by name (status pages by slug).
func SpecFromLive(live *Live) (*Spec, []string, error) {
	// Entries are matched by name, so a team with duplicate names cannot be
	// exported faithfully.
	var probs Problems
	_, d := indexByName(live.Channels, func(c Channel) string { return c.Name }, func(c Channel) int64 { return c.ID })
	probs = append(probs, dupProblems(KindChannel, d)...)
	_, d = indexByName(live.Policies, func(p Policy) string { return p.Name }, func(p Policy) int64 { return p.ID })
	probs = append(probs, dupProblems(KindPolicy, d)...)
	_, d = indexByName(live.Monitors, func(m Monitor) string { return m.Name }, func(m Monitor) int64 { return m.ID })
	probs = append(probs, dupProblems(KindMonitor, d)...)
	if len(probs) > 0 {
		return nil, nil, probs
	}
	n := newLiveNames(live)
	var warnings []string
	s := &Spec{Version: SpecVersion}

	vars := map[string]string{}
	placeholder := func(owner, field string) string {
		v := PlaceholderVar(owner, field)
		key := owner + "\x00" + field
		if prev, ok := vars[v]; ok && prev != key {
			warnings = append(warnings, fmt.Sprintf("%s: two secrets share the variable %s; rename one channel", owner, v))
		}
		vars[v] = key
		return "${" + v + "}"
	}

	for _, c := range sortedBy(live.Channels, func(c Channel) string { return c.Name }) {
		cfg := configMap(c.Config)
		if c.ConfigError != "" {
			warnings = append(warnings, fmt.Sprintf("channel %q: its config cannot be decrypted on the server; only secret placeholders are exported", c.Name))
			cfg = map[string]any{}
			for _, f := range SecretFields(c.Type) {
				cfg[f] = redacted
			}
		}
		for _, f := range SecretFields(c.Type) {
			if v, ok := cfg[f]; ok && !isZero(v) {
				cfg[f] = placeholder(c.Name, f)
			}
		}
		// Anything else the API redacted is a secret too.
		cfg = placeholderRedacted(cfg, c.Name, "", placeholder).(map[string]any)
		raw, err := json.Marshal(cfg)
		if err != nil {
			return nil, nil, err
		}
		s.Channels = append(s.Channels, ChannelSpec{Name: c.Name, Type: c.Type, IsDefault: c.IsDefault, Config: raw})
	}

	for _, p := range sortedBy(live.Policies, func(p Policy) string { return p.Name }) {
		ps := PolicySpec{Name: p.Name, Steps: []StepSpec{}}
		for _, st := range p.Steps {
			ps.Steps = append(ps.Steps, StepSpec{Channels: n.channelNames(st.ChannelIDs), DelayS: st.DelayS})
		}
		s.EscalationPolicies = append(s.EscalationPolicies, ps)
	}

	slos := map[int64]SLOListItem{}
	for _, e := range live.SLOs {
		slos[e.MonitorID] = e
	}
	for _, m := range sortedBy(live.Monitors, func(m Monitor) string { return m.Name }) {
		cfg := liveMonitorConfig(m, n)
		if h, ok := cfg["docker_host"].(string); ok && strings.HasPrefix(h, "#") {
			return nil, nil, fmt.Errorf("monitor %q: its Docker host %s is not visible to this token", m.Name, h)
		}
		cfg = placeholderRedacted(cfg, m.Name, "", placeholder).(map[string]any)
		raw, err := json.Marshal(cfg)
		if err != nil {
			return nil, nil, err
		}
		ms := MonitorSpec{
			Name: m.Name, Type: m.Type, Config: raw,
			IntervalS: new(m.IntervalS), RetryIntervalS: new(m.RetryIntervalS), Retries: new(m.Retries), TimeoutS: new(m.TimeoutS),
			Paused: m.Paused, GroupName: m.GroupName, Tags: m.Tags,
		}
		regions := m.Regions
		if len(regions) == 0 {
			regions = []string{localRegion}
		}
		if !slices.Equal(regions, []string{localRegion}) {
			ms.Regions = slices.Clone(regions)
		}
		if q := max(m.Quorum, 1); q != defaultQuorum(len(regions)) {
			ms.Quorum = new(q)
		}
		if m.ParentID != nil {
			ms.Parent = nameOf(n.monitors, *m.ParentID)
		}
		if m.EscalationPolicyID != nil {
			ms.EscalationPolicy = nameOf(n.policies, *m.EscalationPolicyID)
		}
		if len(m.ChannelIDs) > 0 {
			ms.Channels = slices.Sorted(slices.Values(n.channelNames(m.ChannelIDs)))
		}
		if e, ok := slos[m.ID]; ok {
			ms.SLO = &SLOSpec{Target: new(e.Target), WindowDays: new(e.WindowDays), FastBurn: new(e.FastBurn), SlowBurn: new(e.SlowBurn)}
		}
		s.Monitors = append(s.Monitors, ms)
	}

	for _, p := range sortedBy(live.StatusPages, func(p StatusPage) string { return p.Slug }) {
		ps := StatusPageSpec{
			Slug: p.Slug, Title: p.Title, Description: p.Description, LogoURL: p.LogoURL,
			Published: p.Published, CustomDomain: p.CustomDomain,
		}
		if p.Theme != defaultTheme {
			ps.Theme = p.Theme
		}
		// Consecutive items of the same section form one section entry, so
		// the display order survives a round trip.
		for _, it := range p.Items {
			name := nameOf(n.monitors, it.MonitorID)
			item := ItemSpec{Monitor: name}
			if def := specItems(StatusPageSpec{Sections: []SectionSpec{{Items: []ItemSpec{{Monitor: name}}}}}); it.DisplayName != def[0].DisplayName {
				item.DisplayName = it.DisplayName
			}
			if k := len(ps.Sections); k > 0 && ps.Sections[k-1].Name == it.Section {
				ps.Sections[k-1].Items = append(ps.Sections[k-1].Items, item)
			} else {
				ps.Sections = append(ps.Sections, SectionSpec{Name: it.Section, Items: []ItemSpec{item}})
			}
		}
		s.StatusPages = append(s.StatusPages, ps)
	}
	return s, warnings, nil
}

// placeholderRedacted replaces every string equal to the redaction marker
// in v with a ${ENV} placeholder named after owner and the key path.
func placeholderRedacted(v any, owner, path string, placeholder func(owner, field string) string) any {
	switch x := v.(type) {
	case map[string]any:
		for k, e := range x {
			x[k] = placeholderRedacted(e, owner, joinPath(path, k), placeholder)
		}
		return x
	case []any:
		for i, e := range x {
			x[i] = placeholderRedacted(e, owner, fmt.Sprintf("%s_%d", path, i), placeholder)
		}
		return x
	case string:
		if x == redacted {
			return placeholder(owner, path)
		}
	}
	return v
}
