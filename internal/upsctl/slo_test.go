func sloProblems(t *testing.T, slo string) error {
	t.Helper()
	s := mustParse(t, "version: 1\nmonitors:\n  - name: api\n    type: tcp\n    config: {host: a, port: 1}\n    slo: "+slo+"\n", nil)
	return upsctl.Validate(s)
}

func TestSLOSpec(t *testing.T) {
	s := mustParse(t, `
version: 1
monitors:
  - name: api
    type: http
    config: {url: "https://${UPSERA_HOST}/health"}
    slo: {target: 99.9}
  - name: db
    type: tcp
    config: {host: db, port: 5432}
    slo: {target: 99.5, window_days: 7, fast_burn: 10, slow_burn: 10}
`, env(map[string]string{"UPSERA_HOST": "api.example.com"}))
	if err := upsctl.Validate(s); err != nil {
		t.Fatal(err)
	}
	api := s.Monitors[0]
	if api.SLO == nil || *api.SLO.Target != 99.9 || api.SLO.WindowDays != nil || api.SLO.FastBurn != nil || api.SLO.SlowBurn != nil {
		t.Fatalf("slo = %+v", api.SLO)
	}
	if !strings.Contains(string(api.Config), "https://api.example.com/health") {
		t.Fatalf("config not expanded: %s", api.Config)
	}

	for _, slo := range []string{
		"{target: 0.001}", "{target: 99.999}", "{target: 50, window_days: 90}", "{target: 99, fast_burn: 1000, slow_burn: 1}",
		"{target: 99, slow_burn: 14.4}", "{target: 99.900}",
	} {
		if err := sloProblems(t, slo); err != nil {
			t.Errorf("%s: %v", slo, err)
		}
	}
	for slo, want := range map[string]string{
		"{window_days: 30}":                           "monitors[0] (api): slo.target is required",
		"{target: 0}":                                 "slo.target must be greater than 0 and less than 100",
		"{target: 100}":                               "slo.target must be greater than 0 and less than 100",
		"{target: -1}":                                "slo.target must be greater than 0 and less than 100",
		"{target: 99.9999}":                           "slo.target must have at most 3 decimals",
		"{target: 99, window_days: 6}":                "slo.window_days must be between 7 and 90",
		"{target: 99, window_days: 91}":               "slo.window_days must be between 7 and 90",
		"{target: 99, slow_burn: 0.5}":                "slo.slow_burn must be at least 1",
		"{target: 99, fast_burn: 5}":                  "slo.fast_burn must be at least slow_burn",
		"{target: 99, slow_burn: 20}":                 "slo.fast_burn must be at least slow_burn",
		"{target: 99, fast_burn: 1000.5}":             "slo.fast_burn must be at most 1000",
		"{target: 99, fast_burn: 2000, slow_burn: 3}": "slo.fast_burn must be at most 1000",
	} {
		err := sloProblems(t, slo)
		var p upsctl.Problems
		if err == nil || !errors.As(err, &p) || !strings.Contains(err.Error(), want) {
			t.Errorf("%s: err = %v, want %q", slo, err, want)
		}
	}
	if got := parseErr(t, "version: 1\nmonitors:\n  - {name: a, type: tcp, slo: {target: 99, burn: 2}}\n", nil); !strings.Contains(got, "monitors[0].slo.burn: unknown field") {
		t.Fatalf("unknown slo key: %q", got)
	}
}

const sloSpec = `
version: 1
monitors:
  - name: api
    type: http
    parent: db
    config: {url: "https://api.example.com/health"}
    slo: {target: 99.9}
  - name: db
    type: tcp
    config: {host: db.internal, port: 5432}
    slo: {target: 99.5, window_days: 7, fast_burn: 10, slow_burn: 2}
`

func TestSLOExportGolden(t *testing.T) {
	f := newFakeAPI()
	apply(t, f, sloSpec, false)
	y, _, err := upsctl.Export(context.Background(), f)
	if err != nil {
		t.Fatal(err)
	}
	want := `# generated by upsctl, secrets are ${ENV} placeholders
version: 1
monitors:
- config:
    url: https://api.example.com/health
  interval_s: 60
  name: api
  parent: db
  retries: 1
  retry_interval_s: 20
  slo:
    fast_burn: 14.4
    slow_burn: 6
    target: 99.9
    window_days: 30
  timeout_s: 10
  type: http
- config:
    host: db.internal
    port: 5432
  interval_s: 60
  name: db
  retries: 1
  retry_interval_s: 20
  slo:
    fast_burn: 10
    slow_burn: 2
    target: 99.5
    window_days: 7
  timeout_s: 10
  type: tcp
`
	if string(y) != want {
		t.Fatalf("export:\n%s\nwant:\n%s", y, want)
	}

	g := newFakeAPI()
	s, err := upsctl.Parse("export.yaml", y, env(nil))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := upsctl.Apply(context.Background(), g, s, upsctl.ApplyOptions{}); err != nil {
		t.Fatal(err)
	}
	y2, _, err := upsctl.Export(context.Background(), g)
	if err != nil || string(y2) != want {
		t.Fatalf("round trip: %v\n%s", err, y2)
	}
}

func TestSLOPlanApply(t *testing.T) {
	f := newFakeAPI()
	apply(t, f, sloSpec, false)
	want := []string{"create monitor db", "put slo db", "create monitor api", "put slo api"}
	if got := f.takeWrites(); !slices.Equal(got, want) {
		t.Fatalf("writes = %q, want %q", got, want)
	}
	if got := f.slo("api"); got.Target != 99.9 || got.WindowDays != 30 || got.FastBurn != 14.4 || got.SlowBurn != 6 {
		t.Fatalf("api slo = %+v", got)
	}

	// Unchanged: no PUT, diff exits 0, also when the target is written
	// with trailing zeros.
	res, out := apply(t, f, sloSpec, false)
	if res.Changed() || len(f.takeWrites()) != 0 {
		t.Fatalf("second apply: %+v\n%s", res, out)
	}
	for _, spec := range []string{sloSpec, strings.Replace(sloSpec, "slo: {target: 99.9}", "slo: {target: 99.900, window_days: 30, fast_burn: 14.4, slow_burn: 6}", 1)} {
		if code, out := diff(t, f, spec, false); code != upsctl.ExitNoChanges || !strings.Contains(out, "No changes.") {
			t.Fatalf("diff exit %d:\n%s", code, out)
		}
	}

	// A real difference is an update.
	changed := strings.Replace(sloSpec, "slo: {target: 99.9}", "slo: {target: 99.95, window_days: 28}", 1)
	code, out := diff(t, f, changed, false)
	wantOut := "~ update monitor \"api\": slo target 99.9 -> 99.95, slo window_days 30 -> 28\nPlan: 0 to create, 1 to update, 0 to delete.\n"
	if code != upsctl.ExitChanges || out != wantOut {
		t.Fatalf("diff exit %d:\n%s\nwant:\n%s", code, out, wantOut)
	}
	res, out = apply(t, f, changed, false)
	if res.Updated != 1 || !slices.Equal(f.takeWrites(), []string{"put slo api"}) || !strings.Contains(out, `updated monitor "api" slo (target 99.9 -> 99.95, window_days 30 -> 28)`) {
		t.Fatalf("update: %+v\n%s", res, out)
	}

	// An SLO the spec drops is kept without --prune, deleted with it.
	dropped := strings.Replace(changed, "    slo: {target: 99.95, window_days: 28}\n", "", 1)
	code, out = diff(t, f, dropped, false)
	if code != upsctl.ExitNoChanges || !strings.Contains(out, `not managed, kept: monitor "api" slo (use --prune to delete)`) {
		t.Fatalf("diff without prune: exit %d\n%s", code, out)
	}
	if res, _ := apply(t, f, dropped, false); res.Changed() || len(f.takeWrites()) != 0 {
		t.Fatal("apply without --prune touched the slo")
	}
	code, out = diff(t, f, dropped, true)
	if code != upsctl.ExitChanges || out != "- delete monitor \"api\" slo\nPlan: 0 to create, 0 to update, 1 to delete.\n" {
		t.Fatalf("diff --prune: exit %d\n%s", code, out)
	}
	res, out = apply(t, f, dropped, true)
	if res.Deleted != 1 || !slices.Equal(f.takeWrites(), []string{"delete slo api"}) || !strings.Contains(out, `deleted monitor "api" slo`) {
		t.Fatalf("prune: %+v\n%s", res, out)
	}

	// A new SLO on an existing monitor is a create.
	code, out = diff(t, f, changed, false)
	if code != upsctl.ExitChanges || !strings.Contains(out, `+ create monitor "api" slo: target 99.95, window_days 28, fast_burn 14.4, slow_burn 6`) {
		t.Fatalf("diff create: exit %d\n%s", code, out)
	}
}

func TestSLOPruneMonitorCascades(t *testing.T) {
	f := newFakeAPI()
	apply(t, f, sloSpec, false)
	f.takeWrites()
	onlyDB := "version: 1\nmonitors:\n  - name: db\n    type: tcp\n    config: {host: db.internal, port: 5432}\n    slo: {target: 99.5, window_days: 7, fast_burn: 10, slow_burn: 2}\n"
	res, _ := apply(t, f, onlyDB, true)
	if got := f.takeWrites(); !slices.Equal(got, []string{"delete monitor api"}) || res.Deleted != 1 {
		t.Fatalf("writes = %q (%+v)", got, res)
	}
}

