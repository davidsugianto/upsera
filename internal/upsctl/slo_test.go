func TestSLOPutErrorStopsApply(t *testing.T) {
	f := newFakeAPI()
	f.failOn = "put slo db"
	var out bytes.Buffer
	res, err := upsctl.Apply(context.Background(), f, mustParse(t, sloSpec, nil), upsctl.ApplyOptions{Out: &out})
	if err == nil || !strings.Contains(err.Error(), `apply stopped at create monitor "db" slo after 1 change(s)`) {
		t.Fatalf("err = %v", err)
	}
	if res.Created != 1 || !strings.Contains(out.String(), `created monitor "db"`) || strings.Contains(out.String(), `created monitor "api"`) {
		t.Fatalf("%+v\n%s", res, out.String())
	}
	if got := f.takeWrites(); !slices.Equal(got, []string{"create monitor db"}) {
		t.Fatalf("writes = %q", got)
	}
}
