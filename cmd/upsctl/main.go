// Command upsctl manages an Upsera team's monitors, channels, escalation
// policies and status pages as YAML: export, diff, apply. The logic is in
// internal/upsctl; this file only wires the commands.
package main

import (
	"bufio"
	"context"
	"errors"
	"fmt"
	"io"
	"os"
	"os/signal"
	"strings"

	"github.com/spf13/cobra"

	"github.com/davidsugianto/upsera/internal/upsctl"
)

// version is set at build time with -ldflags "-X main.version=...".
var version = "dev"

const longHelp = `upsctl keeps an Upsera team's setup in YAML ("monitors as code").

It talks to the REST API with a team API token: UPSERA_URL is the server's
base URL and UPSERA_TOKEN the token (ups_...; apply needs write scope). The
--url and --token flags override them. The token is never printed.

The spec (version: 1) has the keys channels, escalation_policies, monitors
and status_pages. Field names are the API's JSON names; entries refer to
each other by name, never by id (a status page by its slug):
  monitors[].parent, .escalation_policy, .channels   names
  monitors[].config.docker_host                      Docker host name (docker monitors)
  escalation_policies[].steps[].channels             channel names
  status_pages[].sections[].items[].monitor          monitor names
Unknown keys are errors.

A monitor may have one SLO: slo: {target: 99.9, window_days: 30,
fast_burn: 14.4, slow_burn: 6}. target (percent, 0 < target < 100, at most 3
decimals) is required; the others default to the values shown (window 7..90
days, 1 <= slow_burn <= fast_burn <= 1000). Export always writes all four.
An SLO removed from the spec is kept unless apply runs with --prune.

Secrets: export never writes a secret. Every secret channel field is written
as a ${UPSERA_<CHANNEL>_<FIELD>} placeholder (e.g. ${UPSERA_ONCALL_BOT_TOKEN});
diff and apply read it from the environment. Placeholders are expanded in
string values only, $$ is a literal $, an unset variable is an error, and only
UPSERA_* variables other than UPSERA_TOKEN and UPSERA_URL may be used. Secrets
cannot be compared with what the server holds, so apply always re-sends them
(an unchanged channel is not rewritten) and diff says "secrets not compared".
Webhook headers take a JSON object in their variable.

Push monitors: the push URL (its token) is generated by each server and is
not part of the spec, so after applying to another instance, copy the new
push URLs from the dashboard into the jobs that push.

Status page custom domains can only be set by an instance admin in the
dashboard: export includes them, apply leaves them unchanged with a warning.`

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt)
	code := run(ctx, os.Args[1:], os.Stdin, os.Stdout, os.Stderr, os.LookupEnv)
	stop()
	os.Exit(code)
}

// exitError carries a specific exit code (diff's 2) without a message.
type exitError struct{ code int }

func (e exitError) Error() string { return fmt.Sprintf("exit %d", e.code) }

func run(ctx context.Context, args []string, stdin io.Reader, stdout, stderr io.Writer, lookup upsctl.LookupFunc) int {
	cmd := newRootCmd(stdin, stdout, stderr, lookup)
	cmd.SetArgs(args)
	err := cmd.ExecuteContext(ctx)
	var ee exitError
	switch {
	case err == nil:
		return 0
	case errors.As(err, &ee):
		return ee.code
	default:
		fmt.Fprintf(stderr, "upsctl: %v\n", err)
		return upsctl.ExitError
	}
}

type globalFlags struct {
	url, token string
}

func newRootCmd(stdin io.Reader, stdout, stderr io.Writer, lookup upsctl.LookupFunc) *cobra.Command {
	g := &globalFlags{}
	root := &cobra.Command{
		Use:           "upsctl",
		Short:         "Export, diff and apply an Upsera team's setup as YAML",
		Long:          longHelp,
		SilenceUsage:  true,
		SilenceErrors: true,
	}
	root.SetIn(stdin)
	root.SetOut(stdout)
	root.SetErr(stderr)
	root.PersistentFlags().StringVar(&g.url, "url", "", "Upsera base URL (default $UPSERA_URL)")
	root.PersistentFlags().StringVar(&g.token, "token", "", "team API token (default $UPSERA_TOKEN)")

	client := func() (*upsctl.Client, error) {
		url, token := g.url, g.token
		if url == "" {
			url, _ = lookup("UPSERA_URL")
		}
		if token == "" {
			token, _ = lookup("UPSERA_TOKEN")
		}
		if url == "" {
			return nil, errors.New("no server URL: set UPSERA_URL or pass --url")
		}
		if token == "" {
			return nil, errors.New("no API token: set UPSERA_TOKEN or pass --token")
		}
		if !strings.HasPrefix(url, "http://") && !strings.HasPrefix(url, "https://") {
			return nil, errors.New("the server URL must start with http:// or https://")
		}
		return upsctl.NewClient(url, token), nil
	}

	root.AddCommand(&cobra.Command{
		Use:   "version",
		Short: "Print the upsctl version",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			fmt.Fprintln(cmd.OutOrStdout(), "upsctl", version)
			return nil
		},
	})

	var outFile string
	export := &cobra.Command{
		Use:   "export",
		Short: "Write the live team as a YAML spec (secrets as ${ENV} placeholders)",
		Long: "Export reads the token's team and writes it as a spec: sorted by name (status pages by slug),\n" +
			"no ids or timestamps, every secret as a ${UPSERA_<CHANNEL>_<FIELD>} placeholder.",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			c, err := client()
			if err != nil {
				return err
			}
			y, warnings, err := upsctl.Export(cmd.Context(), c)
			if err != nil {
				return err
			}
			for _, w := range warnings {
				fmt.Fprintln(cmd.ErrOrStderr(), "warning:", w)
			}
			if outFile == "" || outFile == "-" {
				_, err = cmd.OutOrStdout().Write(y)
				return err
			}
			return os.WriteFile(outFile, y, 0o644)
		},
	}
	export.Flags().StringVarP(&outFile, "output", "o", "", "write to this file instead of stdout")
	root.AddCommand(export)

	var diffFiles []string
	var diffPrune bool
	diff := &cobra.Command{
		Use:   "diff -f FILE [-f FILE ...]",
		Short: "Show what apply would change",
		Long: "Diff compares the spec (several -f files are merged) with the live team and prints\n" +
			"+ create, ~ update (with the changed fields) and, with --prune, - delete.\n" +
			"Exit code: 0 nothing would change, 2 something would, 1 error.",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			s, err := upsctl.LoadFiles(diffFiles, lookup)
			if err != nil {
				return err
			}
			c, err := client()
			if err != nil {
				return err
			}
			changed, err := upsctl.Diff(cmd.Context(), c, s, diffPrune, cmd.OutOrStdout())
			if code := upsctl.DiffExitCode(changed, err); code == upsctl.ExitChanges {
				return exitError{code: code}
			}
			return err
		},
	}
	diff.Flags().StringArrayVarP(&diffFiles, "file", "f", nil, "spec file (repeatable)")
	diff.Flags().BoolVar(&diffPrune, "prune", false, "also show deletes of live entries the spec does not list")
	_ = diff.MarkFlagRequired("file")
	root.AddCommand(diff)

	var applyFiles []string
	var prune, yes bool
	apply := &cobra.Command{
		Use:   "apply -f FILE [-f FILE ...] [--prune] [--yes]",
		Short: "Make the live team match the spec",
		Long: "Apply creates and updates channels, escalation policies, monitors (parents first) and\n" +
			"status pages, in that order. With --prune it then deletes, in reverse order, what the spec\n" +
			"does not list; without it those entries are listed as \"not managed, kept\". Every check\n" +
			"runs before the first write; on an API error apply stops and the lines above say what was\n" +
			"applied. Without --yes it asks for confirmation (and refuses when stdin is not a terminal).",
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			s, err := upsctl.LoadFiles(applyFiles, lookup)
			if err != nil {
				return err
			}
			c, err := client()
			if err != nil {
				return err
			}
			opts := upsctl.ApplyOptions{Prune: prune, Out: cmd.OutOrStdout()}
			if !yes {
				opts.Confirm = func() (bool, error) { return confirm(cmd.InOrStdin(), cmd.OutOrStdout()) }
			}
			_, err = upsctl.Apply(cmd.Context(), c, s, opts)
			return err
		},
	}
	apply.Flags().StringArrayVarP(&applyFiles, "file", "f", nil, "spec file (repeatable)")
	apply.Flags().BoolVar(&prune, "prune", false, "delete live entries the spec does not list")
	apply.Flags().BoolVarP(&yes, "yes", "y", false, "apply without asking")
	_ = apply.MarkFlagRequired("file")
	root.AddCommand(apply)
	return root
}

// confirm asks on a terminal; anything else needs --yes.
func confirm(in io.Reader, out io.Writer) (bool, error) {
	f, ok := in.(*os.File)
	if !ok || !isTerminal(f) {
		return false, errors.New("refusing to apply without --yes: stdin is not a terminal")
	}
	fmt.Fprint(out, "Apply these changes? [y/N] ")
	line, err := bufio.NewReader(in).ReadString('\n')
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}
	answer := strings.ToLower(strings.TrimSpace(line))
	return answer == "y" || answer == "yes", nil
}

func isTerminal(f *os.File) bool {
	st, err := f.Stat()
	return err == nil && st.Mode()&os.ModeCharDevice != 0
}
